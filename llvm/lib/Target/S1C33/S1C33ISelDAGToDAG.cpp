// Match (CopyFromReg SP) optionally plus a non-negative ConstantSDNode offset.
// Returns true and writes the byte offset (0 when Addr is CopyFromReg alone) on
// success.  Used by the LOAD/STORE selection cases to emit Class-2 SP-relative
// instructions for outgoing call stack arguments, whose addresses arrive as
// (add (CopyFromReg SP), imm) rather than as a FrameIndex.
static bool matchSPPlusConstAddr(SDValue Addr, int64_t &ByteOffOut) {
  auto IsCopyFromSP = [](SDValue V) {
    if (V.getOpcode() != ISD::CopyFromReg)
      return false;
    auto *R = dyn_cast<RegisterSDNode>(V.getOperand(1));
    return R && R->getReg() == S1C33::SP;
  };
  if (IsCopyFromSP(Addr)) {
    ByteOffOut = 0;
    return true;
  }
  if (Addr.getOpcode() == ISD::ADD && IsCopyFromSP(Addr.getOperand(0))) {
    auto *C = dyn_cast<ConstantSDNode>(Addr.getOperand(1));
    if (!C)
      return false;
    int64_t Off = C->getSExtValue();
    if (Off < 0)
      return false;
    ByteOffOut = Off;
    return true;
  }
  return false;
}

void S1C33DAGToDAGISel::Select(SDNode *Node) {
  if (Node->isMachineOpcode()) {
    Node->setNodeId(-1);
    return;
  }

  SDLoc DL(Node);

  switch (Node->getOpcode()) {
  case ISD::FrameIndex: {
    // Convert ISD::FrameIndex to ISD::TargetFrameIndex so that TableGen
    // patterns using (frameindex:$fi) can match it in load/store addresses.
    //
    // However, when FrameIndex is used as a plain *value* (not the address
    // operand of a load/store) — e.g. in a CopyToReg to pass an alloca
    // address into a loop — TargetFrameIndex is a leaf with no VR. The
    // InstrEmitter then calls getVR(TargetFrameIndex) and asserts because no
    // virtual register was ever assigned for it.
    //
    // Detect this: if any use is NOT a load/store using this node as its
    // base-address operand, wrap the TargetFrameIndex in an ADJFI pseudo
    // (which produces a real VR and is later expanded by eliminateFrameIndex
    // to LDW_from_SP + ADD_ri).  For purely address uses, TargetFrameIndex
    // alone is sufficient and the *_sp patterns stay efficient.
    int FI = cast<FrameIndexSDNode>(Node)->getIndex();
    SDValue TFI = CurDAG->getTargetFrameIndex(FI, MVT::i32);

    // Check all uses: if any use requires a real VR, wrap in ADJFI.
    //
    // DAG isel is top-down: by the time Select(FrameIndex) runs, parent nodes
    // may already be machine opcodes.  Two kinds of machine-opcode users:
    //
    //  A) Memory instructions (LDW_sp, STW_sp, LDW_ri, ...) and ADJFI:
    //     these hold a MO_FrameIndex operand which eliminateFrameIndex handles.
    //     TargetFrameIndex is safe here.
    //
    //  B) All other machine opcodes (SELECT, ADD, CMP, ...):
    //     they expect a register operand.  TargetFrameIndex would be emitted as
    //     MO_FrameIndex and getReg() would assert later.
    //     NeedsVR = true for these.
    //
    // For un-morphed ISD nodes, only ISD::LOAD/STORE with FrameIndex as the
    // base pointer are safe; everything else (CopyToReg, ADD, SELECT, ...) needs
    // a VR.
    bool NeedsVR = false;
    for (SDUse &Use : Node->uses()) {
      SDNode *User = Use.getUser();
      if (User->isMachineOpcode()) {
        unsigned MachOpc = User->getMachineOpcode();
        // ADJFI: designed to hold a TargetFrameIndex operand.
        if (MachOpc == S1C33::ADJFI)
          continue;
        // Memory instructions have the address at SDNode operand 0.
        // Only that position is safe with TargetFrameIndex; value operands
        // (e.g. storing the address of a local variable) need a real VR.
        const TargetInstrInfo *TII =
            CurDAG->getSubtarget().getInstrInfo();
        const MCInstrDesc &Desc = TII->get(MachOpc);
        if ((Desc.mayLoad() || Desc.mayStore()) && Use.getOperandNo() == 0)
          continue;
        NeedsVR = true;
        break;
      }
      // Un-morphed ISD node: safe only for load/store address uses.
      unsigned UseOpc = User->getOpcode();
      SDValue Addr;
      if (UseOpc == ISD::LOAD)
        Addr = cast<LoadSDNode>(User)->getBasePtr();
      else if (UseOpc == ISD::STORE)
        Addr = cast<StoreSDNode>(User)->getBasePtr();
      if (Addr.getNode() != Node) {
        NeedsVR = true;
        break;
      }
    }

    if (!NeedsVR) {
      ReplaceNode(Node, TFI.getNode());
    } else {
      // Value use (e.g. CopyToReg, ADD): produce a proper VR via ADJFI.
      // load/store users of this same node will get LDW_ri(ADJFI) instead of
      // LDW_sp, which is correct though slightly less compact.
      SDNode *Adj = CurDAG->getMachineNode(S1C33::ADJFI, DL, MVT::i32, TFI);
      ReplaceNode(Node, Adj);
    }
    return;
  }

  case ISD::LOAD: {
    // Post-increment load: fuse (load ptr) + (add ptr, size) into ld.X [%rb]+.
    // Only fires when getPostIndexedAddressParts returned true; tryIndexedLoad
    // picks the right LDB/LDUB/LDH/LDUH/LDW_ri_pi opcode based on MemVT and
    // the load's extension type.
    if (tryIndexedLoad(Node))
      return;

    // When loading from a frame-index address, always select the SP-relative
    // instruction (*_sp) rather than the register-indirect (*_ri) form.
    // Without this, SelectCode may select e.g. LDUB_ri with the frame-index
    // in the register slot; eliminateFrameIndex then replaces it with a raw
    // offset, producing invalid assembly like "ld.ub %r4, [43]".
    LoadSDNode *LD = cast<LoadSDNode>(Node);
    SDValue Addr = LD->getBasePtr();

    EVT MemVT = LD->getMemoryVT();
    ISD::LoadExtType Ext = LD->getExtensionType();
    unsigned Opc;
    if (MemVT == MVT::i32)
      Opc = S1C33::LDW_sp;
    else if (MemVT == MVT::i8 && Ext == ISD::ZEXTLOAD)
      Opc = S1C33::LDUB_sp;
    else if (MemVT == MVT::i8)
      Opc = S1C33::LDB_sp;
    else if (MemVT == MVT::i16 && Ext == ISD::ZEXTLOAD)
      Opc = S1C33::LDUH_sp;
    else if (MemVT == MVT::i16)
      Opc = S1C33::LDH_sp;
    else
      break;

    SDValue AddrOp;
    if (Addr.getOpcode() == ISD::TargetFrameIndex) {
      AddrOp = Addr;
    } else {
      // Match (CopyFromReg SP) [± const] for outgoing call stack arguments,
      // whose addresses are not frame-indexed.  Encode the scaled offset
      // directly; eliminateFrameIndex is not involved for this path.
      int64_t Off;
      if (!matchSPPlusConstAddr(Addr, Off))
        break;
      unsigned Scale = (Opc == S1C33::LDW_sp) ? 4 :
                       (Opc == S1C33::LDH_sp || Opc == S1C33::LDUH_sp) ? 2 : 1;
      if ((Off % Scale) != 0 || uint64_t(Off / Scale) >= 64)
        break;
      AddrOp = CurDAG->getTargetConstant(Off / Scale, DL, MVT::i32);
    }

    SDNode *New = CurDAG->getMachineNode(Opc, DL, {MVT::i32, MVT::Other},
                                         {AddrOp, LD->getChain()});
    CurDAG->setNodeMemRefs(cast<MachineSDNode>(New), {LD->getMemOperand()});
    ReplaceUses(SDValue(Node, 0), SDValue(New, 0));
    ReplaceUses(SDValue(Node, 1), SDValue(New, 1));
    CurDAG->RemoveDeadNode(Node);
    return;
  }

  case ISD::STORE: {
    // Post-increment store: fuse (store val, ptr) + (add ptr, size) into
    // ld.X [%rb]+, %rs.  tryIndexedStore picks the right opcode based on
    // MemVT and handles truncating stores (i32→i8, i32→i16).
    if (tryIndexedStore(Node))
      return;

    // Same as LOAD: force SP-relative stores when address is a frame index.
    StoreSDNode *ST = cast<StoreSDNode>(Node);
    SDValue Addr = ST->getBasePtr();

    EVT MemVT = ST->getMemoryVT();
    unsigned Opc;
    if (MemVT == MVT::i32)
      Opc = S1C33::STW_sp;
    else if (MemVT == MVT::i8)
      Opc = S1C33::STB_sp;
    else if (MemVT == MVT::i16)
      Opc = S1C33::STH_sp;
    else
      break;

    SDValue AddrOp;
    if (Addr.getOpcode() == ISD::TargetFrameIndex) {
      AddrOp = Addr;
    } else {
      // Match (CopyFromReg SP) [+ const] for outgoing call stack arguments.
      // These arrive as (add (CopyFromReg SP), imm) rather than frame indices.
      int64_t Off;
      if (!matchSPPlusConstAddr(Addr, Off))
        break;
      unsigned Scale = (Opc == S1C33::STW_sp) ? 4 :
                       (Opc == S1C33::STH_sp) ? 2 : 1;
      if ((Off % Scale) != 0 || uint64_t(Off / Scale) >= 64)
        break;
      AddrOp = CurDAG->getTargetConstant(Off / Scale, DL, MVT::i32);
    }

    // STX_sp operand order: (ins mem_sp:$imm6, GR32:$rd)
    SDNode *New = CurDAG->getMachineNode(Opc, DL, MVT::Other,
                                         {AddrOp, ST->getValue(), ST->getChain()});
    CurDAG->setNodeMemRefs(cast<MachineSDNode>(New), {ST->getMemOperand()});
    ReplaceUses(SDValue(Node, 0), SDValue(New, 0));
    CurDAG->RemoveDeadNode(Node);
    return;
  }

  case ISD::SHL:
  case ISD::SRL:
  case ISD::SRA: {
    // Shift instructions cannot use ext; max immediate is 8.
    // For constant shifts > 8, emit a chain of machine shift instructions
    // (each ≤ 8) here in the selector. Using machine nodes (getMachineNode)
    // bypasses the generic DAG combiner, preventing it from re-merging the
    // chain back into a single large-count shift (which would infinite-loop
    // if done via PerformDAGCombine).
    ConstantSDNode *C = dyn_cast<ConstantSDNode>(Node->getOperand(1));
    if (!C || C->getZExtValue() <= 8)
      break;

    unsigned Opc;
    switch (Node->getOpcode()) {
    case ISD::SHL: Opc = S1C33::SLL_ri; break;
    case ISD::SRL: Opc = S1C33::SRL_ri; break;
    default:       Opc = S1C33::SRA_ri; break;
    }

    uint64_t Count = C->getZExtValue();
    SDValue Val = Node->getOperand(0);

    while (Count > 0) {
      uint64_t Step = (Count > 8) ? 8 : Count;
      Val = SDValue(CurDAG->getMachineNode(
                        Opc, DL, MVT::i32,
                        {Val, CurDAG->getTargetConstant(Step, DL, MVT::i32)}),
                    0);
      Count -= Step;
    }
    ReplaceNode(Node, Val.getNode());
    return;
  }

  case ISD::AND:
  case ISD::OR:
  case ISD::XOR: {
    // For constants requiring two ext prefixes (outside ±2^18), split into:
    //   MOV_ri32 %tmp, const    ← trivially loop-invariant
    //   ANDxx_rr %rd, %tmp       ← in-loop register operation
    // MachineLICM can then hoist the MOV_ri32 out of any enclosing loop.
    // Constants in the ±2^18 range (single ext) fall through to AND_ri32 pseudo,
    // which expands post-RA to "ext imm13; and %rd, imm6" — 2 instructions
    // and suitable for single-use cases.
    SDValue LHS = Node->getOperand(0);
    SDValue RHS = Node->getOperand(1);
    // Normalise: constant on RHS.
    if (isa<ConstantSDNode>(LHS) && !isa<ConstantSDNode>(RHS))
      std::swap(LHS, RHS);
    auto *C = dyn_cast<ConstantSDNode>(RHS);
    if (!C || isInt<19>(C->getSExtValue()))
      break;

    unsigned Opc;
    switch (Node->getOpcode()) {
    case ISD::AND: Opc = S1C33::AND_rr; break;
    case ISD::OR:  Opc = S1C33::OR_rr;  break;
    default:       Opc = S1C33::XOR_rr; break;
    }

    SDValue TargetImm =
        CurDAG->getTargetConstant(C->getZExtValue(), DL, MVT::i32);
    MachineSDNode *Mov =
        CurDAG->getMachineNode(S1C33::MOV_ri32, DL, MVT::i32, TargetImm);
    SDNode *Op =
        CurDAG->getMachineNode(Opc, DL, MVT::i32, LHS, SDValue(Mov, 0));
    ReplaceNode(Node, Op);
    return;
  }

  case ISD::MUL: {
    // When both operands are known to fit in 16 bits, use the 1-clock
    // 16×16→32 multiply (mltu.h/mlt.h) instead of 5-clock 32×32 (mlt.w).
    if (!Subtarget->hasHWMul())
      break;
    SDValue LHS = Node->getOperand(0);
    SDValue RHS = Node->getOperand(1);
    KnownBits LHSBits = CurDAG->computeKnownBits(LHS);
    KnownBits RHSBits = CurDAG->computeKnownBits(RHS);
    if (LHSBits.countMaxActiveBits() <= 16 &&
        RHSBits.countMaxActiveBits() <= 16) {
      SDNode *Mul = CurDAG->getMachineNode(S1C33::MUL16U_r, DL, MVT::i32,
                                            LHS, RHS);
      ReplaceNode(Node, Mul);
      return;
    }
    unsigned LHSSign = CurDAG->ComputeNumSignBits(LHS);
    unsigned RHSSign = CurDAG->ComputeNumSignBits(RHS);
    if (LHSSign >= 17 && RHSSign >= 17) {
      SDNode *Mul = CurDAG->getMachineNode(S1C33::MUL16S_r, DL, MVT::i32,
                                            LHS, RHS);
      ReplaceNode(Node, Mul);
      return;
    }
    break;
  }

  default:
    break;
  }

  SelectCode(Node);
}

//===----------------------------------------------------------------------===//
// Post-increment load selection.
//
// LLVM has standard PatFrags for post-indexed stores (post_store,
// post_truncsti8/16/32) but NONE for post-indexed loads — load selection for
// indexed addressing is done manually per target (see MSP430/PPC/ARM).
//
// An IndexedLoadSDNode produces three results: (loaded_value, new_base_ptr,
// chain).  We pick LDB_ri_pi / LDUB_ri_pi / LDH_ri_pi / LDUH_ri_pi / LDW_ri_pi
// based on (MemVT, ExtensionType), materialise the machine node, and rewire
// all three result edges.
//===----------------------------------------------------------------------===//
bool S1C33DAGToDAGISel::tryIndexedLoad(SDNode *N) {
  auto *LD = cast<LoadSDNode>(N);
  if (LD->getAddressingMode() != ISD::POST_INC)
    return false;

  EVT MemVT = LD->getMemoryVT();
  ISD::LoadExtType Ext = LD->getExtensionType();

  unsigned Opc;
  switch (MemVT.getSimpleVT().SimpleTy) {
  case MVT::i8:
    // Non-ext and EXTLOAD of i8 → sign-extending ld.b (matches plain load
    // selection elsewhere — LLVM's i8 result in an i32 GPR is sign-extended
    // by convention unless ZEXTLOAD is specified).
    Opc = (Ext == ISD::ZEXTLOAD) ? S1C33::LDUB_ri_pi : S1C33::LDB_ri_pi;
    break;
  case MVT::i16:
    Opc = (Ext == ISD::ZEXTLOAD) ? S1C33::LDUH_ri_pi : S1C33::LDH_ri_pi;
    break;
  case MVT::i32:
    if (Ext != ISD::NON_EXTLOAD)
      return false;
    Opc = S1C33::LDW_ri_pi;
    break;
  default:
    return false;
  }

  SDLoc DL(N);
  SDValue Base = LD->getBasePtr();
  SDValue Chain = LD->getChain();

  // Real instruction layout (InstrInfo.td):
  //   (outs GR32:$rd, GR32:$rb_out), (ins GR32:$rb)
  //   Constraints: $rb_out = $rb (tied).
  // Result tuple: (i32 rd, i32 rb_out, Other chain).
  SDNode *New = CurDAG->getMachineNode(Opc, DL,
                                        {MVT::i32, MVT::i32, MVT::Other},
                                        {Base, Chain});

  // Transfer MachineMemOperand so alias analysis and scheduler see the mem op.
  CurDAG->setNodeMemRefs(cast<MachineSDNode>(New), {LD->getMemOperand()});

  // Wire outputs: N has (value, updated_base, chain) — replace in kind.
  ReplaceUses(SDValue(N, 0), SDValue(New, 0)); // loaded value
  ReplaceUses(SDValue(N, 1), SDValue(New, 1)); // incremented base
  ReplaceUses(SDValue(N, 2), SDValue(New, 2)); // chain
  CurDAG->RemoveDeadNode(N);
  return true;
}

//===----------------------------------------------------------------------===//
// Post-increment store selection.
//
// Mirror of tryIndexedLoad for StoreSDNode.  Picks STB_ri_pi / STH_ri_pi /
// STW_ri_pi based on MemVT (truncating stores collapse i32→i8/i16 to the
// byte/halfword variants).  Instruction output tuple: (new_base, chain).
//===----------------------------------------------------------------------===//
bool S1C33DAGToDAGISel::tryIndexedStore(SDNode *N) {
  auto *ST = cast<StoreSDNode>(N);
  if (ST->getAddressingMode() != ISD::POST_INC)
    return false;

  unsigned Opc;
  switch (ST->getMemoryVT().getSimpleVT().SimpleTy) {
  case MVT::i8:  Opc = S1C33::STB_ri_pi; break;
  case MVT::i16: Opc = S1C33::STH_ri_pi; break;
  case MVT::i32: Opc = S1C33::STW_ri_pi; break;
  default: return false;
  }

  SDLoc DL(N);
  SDValue Val = ST->getValue();
  SDValue Base = ST->getBasePtr();
  SDValue Chain = ST->getChain();

  // Real instruction layout (InstrInfo.td):
  //   (outs GR32:$rb_out), (ins GR32:$rb, GR32:$rd)
  //   Constraints: $rb_out = $rb (tied).
  // Result tuple: (i32 rb_out, Other chain).
  SDNode *New = CurDAG->getMachineNode(Opc, DL, {MVT::i32, MVT::Other},
                                        {Base, Val, Chain});

  CurDAG->setNodeMemRefs(cast<MachineSDNode>(New), {ST->getMemOperand()});

  // IndexedStoreSDNode produces (updated_base, chain) as results.
  ReplaceUses(SDValue(N, 0), SDValue(New, 0)); // incremented base
  ReplaceUses(SDValue(N, 1), SDValue(New, 1)); // chain
  CurDAG->RemoveDeadNode(N);
  return true;
}

